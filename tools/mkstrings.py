"""Builds renderer/strings.js (TidyTag 2's texts) from languages/src/translations.json, the same
source 1.2's .po files come from ({danish text: {lang: text}}). Run after changing translations.

    python tools/mkstrings.py        (from the project folder)
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, 'languages', 'src', 'translations.json')
OUT = os.path.join(ROOT, 'renderer', 'strings.js')

table = json.load(open(TABLE, encoding='utf-8'))
body = json.dumps(table, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
js = """// GENERATED by tools/mkstrings.py from languages/src/translations.json - do not edit.
// Texts are 1.2's Danish source strings (with & accelerators); t() translates them.
(function (root, factory) {
  const m = factory();
  if (typeof module === 'object' && module.exports) module.exports = m;
  else root.I18N = m;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const LANGS = { da: 'Dansk', en: 'English', de: 'Deutsch', fr: 'Français', it: 'Italiano', sv: 'Svenska', es: 'Español' };
  const S = %s;
  let lang = 'da';

  // Pascal Format: %%d %%s %%x %%.2d %%5s ... filled in order
  function format(s, args) {
    let i = 0;
    return s.replace(/%%(-?)(\d*)(?:\.(\d+))?([dsxuf%%])/g, (m, left, width, prec, kind) => {
      if (kind === '%%') return '%%';
      let v = args[i++];
      if (v === undefined) return m;
      if (kind === 'x') v = Number(v).toString(16).toUpperCase();
      else if (kind === 'f') v = Number(v).toFixed(prec ? +prec : 2);
      else v = String(v);
      if (prec && (kind === 'd' || kind === 'u' || kind === 'x')) v = v.padStart(+prec, '0');
      if (width) v = left ? v.padEnd(+width) : v.padStart(+width);
      return v;
    });
  }

  function t(dk, ...args) {
    const e = S[dk];
    const s = lang === 'da' || !e ? dk : (e[lang] ?? dk);
    return args.length ? format(s, args) : s;
  }

  // '&Filer' -> 'Filer'; '&&' is a literal &
  const label = (s) => s.replace(/&(&?)/g, (m, amp) => amp);
  const mnemonic = (s) => { const m = /&([^&])/.exec(s.replace(/&&/g, '')); return m ? m[1].toLowerCase() : ''; };

  // The [Main] Language setting; else the system language (nb -> da); else English.
  function effectiveLanguage(setting, systemLanguage) {
    const s = String(setting || '').toLowerCase();
    if (LANGS[s]) return s;
    let c = String(systemLanguage || '').slice(0, 2).toLowerCase();
    if (c === 'nb') c = 'da';
    return LANGS[c] ? c : 'en';
  }

  return {
    LANGS, t, label, mnemonic, effectiveLanguage,
    get lang() { return lang; },
    setLang(l) { lang = LANGS[l] ? l : 'en'; },
  };
});
""" % body
open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
print(f'{len(table)} texts -> {OUT}')

    matchFileNames: (paths, mask, underscores, caseMode) => invoke('match_file_names', { paths, mask, underscores, caseMode }),
    // phase 5 (src-tauri/src/files.rs)
    recycle: (paths) => invoke('recycle_cmd', { paths }),
    copyMove: (paths, dir, doMove) => invoke('copy_move_cmd', { paths, dir, doMove }),
    folderCoverFiles: (dirs) => invoke('folder_cover_files_cmd', { dirs }),
    createFolder: (parent, name) => invoke('create_folder_cmd', { parent, name }),
    planExtChange: (paths, kind) => invoke('plan_ext_change_cmd', { paths, kind }),
    savePlaylist: (target, tracks, fullPaths) => invoke('save_playlist', { target, tracks, fullPaths }),
